def main():
    rows = list(csv.DictReader(io.open(CSV_PATH, encoding="utf-8")))
    data = json.load(io.open(DATA_PATH, encoding="utf-8"))
    existing = data.setdefault("exercises", {})
    generated, skipped, missing = 0, 0, []
    for r in rows:
        zh, en = r["标准中文名"], r["英文名"]
        c = make_ctx(zh, en, r["身体部位"], r["器械"], r["目标肌群"])
        if en in existing:
            if "family" not in existing[en]:
                existing[en]["family"] = {
                    "power clean": "power", "barbell clean and press": "power",
                    "barbell one arm snatch": "power", "barbell thruster": "full_body",
                    "barbell full squat": "squat", "barbell front squat": "squat",
                    "barbell deadlift": "hinge", "barbell romanian deadlift": "hinge",
                    "kettlebell swing": "hinge", "farmers walk": "carry",
                }.get(en, "other")
            if "params" not in existing[en]:
                fn = classify(c)
                scheme = MANUAL_SCHEME.get(en) or (fn(c)["scheme"] if fn else "hypertrophy")
                if en in MANUAL_PARAMS:
                    existing[en]["params"] = OrderedDict(
                        (label, OrderedDict([("sets", sets), ("reps", reps), ("rest", rest)]))
                        for label, sets, reps, rest in MANUAL_PARAMS[en]
                    )
                else:
                    existing[en]["params"] = make_params(scheme)
            skipped += 1
            continue
        entry = build_entry(c)
        if entry is None:
            missing.append((zh, en, r["身体部位"], r["器械"]))
            continue
        existing[en] = entry
        generated += 1
    data["schema_version"] = "1.1"
    data.setdefault("review_policy", {})["generated_layer"] = (
        "规则生成层：按动作族模板 + 器械/角度/单双侧差异生成，evidence_level 为 B/C，"
        "review_status 明确标注未复核，不得与已人工复核内容混用处方口径。"
    )
    out = io.open(DATA_PATH, "w", encoding="utf-8")
    json.dump(data, out, ensure_ascii=False, indent=1)
    out.write("\n")
    out.close()
    print(f"CSV 动作数: {len(rows)}")
    print(f"新增生成: {generated}  已存在跳过: {skipped}  未匹配: {len(missing)}")
    for m in missing:
        print("  未匹配:", m)
    steps = [tuple(e.get("steps", [])) for e in existing.values()]
    print(f"条目总数: {len(existing)}  去重后的分步组合数: {len(set(steps))}")
    empty = [k for k, e in existing.items() if not all([e.get("steps"), e.get("cues"), e.get("common_errors"), e.get("breathing"), e.get("safety"), e.get("difficulty")])]
    print("字段缺失条目:", empty or "无")

if __name__ == "__main__":
    main()
