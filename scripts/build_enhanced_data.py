def build_entry(c):
    fn = classify(c)
    if fn is None:
        return None
    d = fn(c)
    level, note = LEVEL_TEXT[d["scheme"]]
    return OrderedDict([
        ("primary_goal", d["goal"]),
        ("movement_pattern", d["pattern"]),
        ("primary_muscles", d["primary"]),
        ("secondary_muscles", d["secondary"]),
        ("steps", d["steps"]),
        ("cues", d["cues"]),
        ("common_errors", d["errors"]),
        ("breathing", d["breathing"]),
        ("programming", PARAM_TEXT[d["scheme"]]),
        ("params", make_params(d["scheme"])),
        ("difficulty", d["difficulty"]),
        ("family", FAMILY_IDS.get(fn.__name__, "other")),
        ("safety", d["safety"]),
        ("evidence_level", level),
        ("sources", []),
        ("review_status", f"{note}；未经人工复核，不能替代教练现场指导"),
    ])

