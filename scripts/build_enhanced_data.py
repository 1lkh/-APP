def classify(c):
    e = c["en_l"]; z = c["zh_l"]

    # 1) 拉伸与活动度（先判定，避免被 "chest"/"spine" 等词带偏）
    if "stretch" in e or "\u62c9\u4f38" in z or "dog" in e:
        return f_stretch

    # 2) 体能/心肺类（必须先于 jump/squat/lunge 判定）
    if any(k in e for k in ("burpee", "mountain climber", "high knees", "jack jump")):
        return f_cardio

    # 3) 爆发类跳跃
    if "jump" in e:
        return f_jump

